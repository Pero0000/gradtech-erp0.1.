import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import { PGlite } from '@electric-sql/pglite';

const migration = readFileSync(new URL(
  '../supabase/migrations/20261110300000_nalog_povijest_aktivnosti_paginacija.sql',
  import.meta.url,
), 'utf8');
const apiSource = readFileSync(new URL('../src/lib/api.ts', import.meta.url), 'utf8');

const companyId = '00000000-0000-0000-0000-000000000001';
const otherCompanyId = '00000000-0000-0000-0000-000000000002';
const userId = '00000000-0000-0000-0000-000000000003';
const orderId = '00000000-0000-0000-0000-000000000004';
const otherOrderId = '00000000-0000-0000-0000-000000000005';

async function setup(t) {
  const db = new PGlite();
  t.after(() => db.close());
  await db.exec(`
    CREATE ROLE anon;
    CREATE ROLE authenticated;
    CREATE SCHEMA auth;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
      SELECT NULLIF(current_setting('request.jwt.claim.sub', true), '')::uuid
    $$;
    CREATE TABLE public.tvrtke (id uuid PRIMARY KEY, aktivna boolean NOT NULL);
    CREATE TABLE public.app_profiles (id uuid PRIMARY KEY, company_id uuid, approved boolean);
    CREATE TABLE public.app_user_permissions (user_id uuid, module text, can_view boolean);
    CREATE FUNCTION public.app_current_company_id() RETURNS uuid
      LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
        SELECT profile.company_id FROM public.app_profiles profile
        JOIN public.tvrtke company ON company.id = profile.company_id
        WHERE profile.id = auth.uid() AND profile.approved AND company.aktivna
      $$;
    CREATE FUNCTION public.app_has_module_permission(p_module text, p_action text) RETURNS boolean
      LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
        SELECT EXISTS (
          SELECT 1 FROM public.app_profiles profile
          JOIN public.app_user_permissions permission ON permission.user_id = profile.id
          WHERE profile.id = auth.uid() AND profile.approved
            AND profile.company_id = public.app_current_company_id()
            AND permission.module = p_module AND permission.can_view
        )
      $$;
    CREATE TABLE public.radni_nalozi (id uuid PRIMARY KEY, company_id uuid NOT NULL);
    CREATE TABLE public.mobile_work_order_audit (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      nalog_id uuid NOT NULL, actor_name text NOT NULL, action text NOT NULL,
      details jsonb NOT NULL DEFAULT '{}'::jsonb, created_at timestamptz NOT NULL DEFAULT now()
    );
    INSERT INTO public.tvrtke VALUES ('${companyId}', true), ('${otherCompanyId}', true);
    INSERT INTO public.app_profiles VALUES ('${userId}', '${companyId}', true);
    INSERT INTO public.app_user_permissions VALUES ('${userId}', 'radni_nalozi', true);
    INSERT INTO public.radni_nalozi VALUES ('${orderId}', '${companyId}'), ('${otherOrderId}', '${otherCompanyId}');
    GRANT SELECT ON public.radni_nalozi, public.mobile_work_order_audit TO authenticated;
    SELECT set_config('request.jwt.claim.sub', '${userId}', false);
  `);
  await db.exec(migration);
  await db.exec(migration);
  await db.exec('SET ROLE authenticated');
  return db;
}

function loadApi(rpcResult) {
  const { outputText } = ts.transpileModule(apiSource, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  });
  const calls = [];
  const module = { exports: {} };
  vm.runInNewContext(outputText, {
    module, exports: module.exports,
    require(name) {
      if (name === './supabase') return { supabase: { rpc: async (...args) => {
        calls.push(args);
        return rpcResult;
      } } };
      return {};
    },
  });
  return { api: module.exports, calls };
}

test('mobile work-order activity history uses stable 50-row keyset pages without cross-company reads', async (t) => {
  const db = await setup(t);
  await db.exec('RESET ROLE');
  for (let index = 0; index < 57; index++) {
    await db.query(
      'INSERT INTO public.mobile_work_order_audit(nalog_id,actor_name,action,created_at) VALUES ($1,$2,$3,$4)',
      [orderId, `Editor ${index}`, 'order_status_changed', '2026-11-05T08:00:00Z'],
    );
  }
  await db.query(
    'INSERT INTO public.mobile_work_order_audit(id,nalog_id,actor_name,action,created_at) VALUES ($1,$2,$3,$4,$5)',
    ['9007199254740993', orderId, 'Editor bigint', 'order_status_changed', '2026-11-05T08:00:00Z'],
  );
  await db.exec('SET ROLE authenticated');
  const first = (await db.query(
    'SELECT * FROM public.get_mobile_work_order_audit($1)', [orderId],
  )).rows;
  assert.equal(first.length, 50);
  assert.deepEqual(first.slice(0, 3).map((entry) => entry.id), ['9007199254740993', '57', '56']);
  const second = (await db.query(
    'SELECT * FROM public.get_mobile_work_order_audit($1,$2,$3)',
    [orderId, first.at(-1).created_at, first.at(-1).id],
  )).rows;
  assert.equal(second.length, 8);
  assert.deepEqual(second.map((entry) => entry.id), ['8', '7', '6', '5', '4', '3', '2', '1']);
  await assert.rejects(
    db.query('SELECT * FROM public.get_mobile_work_order_audit($1,$2,NULL)', [orderId, first.at(-1).created_at]),
    /Nepotpun pokazivač/,
  );
  await assert.rejects(
    db.query('SELECT * FROM public.get_mobile_work_order_audit($1)', [otherOrderId]),
    /Radni nalog nije dostupan u vašoj tvrtki/,
  );
});

test('mobile work-order activity history checks permissions and the API sends only the keyset cursor', async (t) => {
  const db = await setup(t);
  await db.exec('RESET ROLE');
  await db.exec(`DELETE FROM public.app_user_permissions WHERE user_id='${userId}'`);
  await db.exec('SET ROLE authenticated');
  await assert.rejects(
    db.query('SELECT * FROM public.get_mobile_work_order_audit($1)', [orderId]),
    /Nemate pravo pregleda povijesti radnog naloga/,
  );

  const { api, calls } = loadApi({ data: [], error: null });
  await api.fetchMobileWorkOrderAudit(orderId);
  await api.fetchMobileWorkOrderAudit(orderId, { created_at: '2026-11-05T08:00:00Z', id: '9007199254740993' });
  assert.deepEqual(JSON.parse(JSON.stringify(calls)), [
    ['get_mobile_work_order_audit', {
      p_nalog_id: orderId, p_before_created_at: null, p_before_id: null,
    }],
    ['get_mobile_work_order_audit', {
      p_nalog_id: orderId, p_before_created_at: '2026-11-05T08:00:00Z', p_before_id: '9007199254740993',
    }],
  ]);
  const missing = loadApi({ error: { code: 'PGRST202', message: 'function not found' } });
  await assert.rejects(missing.api.fetchMobileWorkOrderAudit(orderId), /20261110300000/);
});
